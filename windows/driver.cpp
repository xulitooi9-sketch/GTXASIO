/* Public binary interface declarations, 64-bit ASIO host calling convention.
 * ASIO enum constants follow the known ABI values; no SDK sources bundled. */
typedef LONG AsioErr;
struct ASIOInt64 { DWORD hi, lo; };
struct ASIOBufferInfo { LONG isInput, channel; void *buffers[2]; };
struct ASIOChannelInfo {
  LONG channel, isInput, isActive, channelGroup, type;
  char name[32];
};
struct ASIOClockSource { LONG index, associatedChannel, associatedGroup, isCurrentSource; char name[32]; };
struct ASIOCallbacks {
  void (*bufferSwitch)(LONG, LONG);
  void (*sampleRateDidChange)(double);
  LONG (*asioMessage)(LONG, LONG, void *, double *);
  void *(*bufferSwitchTimeInfo)(void *, LONG, LONG);
};
static_assert(sizeof(ASIOBufferInfo)==24,"ASIOBufferInfo ABI mismatch");
static_assert(sizeof(ASIOChannelInfo)==52,"ASIOChannelInfo ABI mismatch");
