static bool setvalue(HKEY root,const char *path,const char *name,const char *value) {
  HKEY key;DWORD d;
  LONG err=RegCreateKeyExA(root,path,0,nullptr,0,KEY_SET_VALUE,nullptr,&key,&d);
  if(err!=ERROR_SUCCESS)return false;
  err=RegSetValueExA(key,name,0,REG_SZ,(const BYTE*)value,(DWORD)std::strlen(value)+1);
  RegCloseKey(key);return err==ERROR_SUCCESS;
}
